"""Оригинальная доверенная C++-обёртка для версий Verilator без autowrite coverage."""

from __future__ import annotations

from .workspace import _identifier


def coverage_main_source(top: str) -> str:
    """Вернуть минимальный C++ wrapper из строго проверенного HDL-идентификатора."""
    _identifier(top, "testbench_top")
    return f"""// Generated by verilator-mcp (Apache-2.0).
// A fixed wrapper, never derived from agent-provided C++ or free CLI arguments.
#include "verilated.h"
#include "verilated_cov.h"
#include "V{top}.h"
#include <memory>

int main(int argc, char** argv) {{
    const std::unique_ptr<VerilatedContext> context{{new VerilatedContext}};
    context->commandArgs(argc, argv);
    const std::unique_ptr<V{top}> model{{new V{top}{{context.get()}}}};
    while (!context->gotFinish()) {{
        model->eval();
        if (!model->eventsPending()) break;
        context->time(model->nextTimeSlot());
    }}
    model->final();
    // Old Verilator --binary main does not always emit coverage.dat.
    // Relative output is confined to this simulation's unique working directory.
    context->coveragep()->write("coverage.dat");
    return 0;
}}
"""
